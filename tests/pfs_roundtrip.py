r"""Regression images generated by the unmodified, bundled MkPFS writer.

Run with tools\pfs\python\python.exe -B tests\pfs_roundtrip.py on Windows.
No games, mounts, administrator rights or network access are required.
"""
from pathlib import Path
import contextlib
import hashlib
import io
import json
import random
import shutil
import struct
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools" / "pfs"))
import pfs_worker as worker
from mkpfs import pfs
from mkpfs.exfat_writer import iter_exfat_image


def hashes(folder):
    return {p.relative_to(folder).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in folder.rglob("*") if p.is_file()}


def pack(folder, image, compress=False, signed=False, bits=32):
    with contextlib.redirect_stderr(io.StringIO()), contextlib.redirect_stdout(io.StringIO()):
        return pfs.build_pfs(folder, image, 65536, 2, bits, False, signed,
                             compress, 0, 1, 6, False, False)


def wrap(source, image):
    with contextlib.redirect_stderr(io.StringIO()), contextlib.redirect_stdout(io.StringIO()):
        return pfs.build_pfs_stream_single_file(source_file=source, output_path=image,
            block_size=65536, pfs_version=2, case_insensitive=False, zlib_level=6,
            threshold_gain=0, min_file_gain=0, min_compress_size=0, cpu_count=1, compress=True)


class PfsRoundTrip(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="fpkg-pfs-caffè & tests-")
        self.root = Path(self.temp.name)
        self.source = self.root / "source"
        (self.source / "sce_sys").mkdir(parents=True)
        (self.source / "empty-directory").mkdir()
        (self.source / "data & names").mkdir()
        (self.source / "sce_sys" / "param.json").write_text(json.dumps({
            "titleId": "PPSA99999", "contentId": "UP0000-PPSA99999_00-FFPFSCTEST000001",
            "contentVersion": "01.000.000", "masterVersion": "01.00",
            "sdkVersion": "0x0900000000000000", "requiredSystemSoftwareVersion": "0x0900000000000000",
            "localizedParameters": {"defaultLanguage": "en-US", "en-US": {"titleName": "FFPFSC synthetic test"}}
        }), encoding="utf-8")
        (self.source / "empty.bin").touch()
        rng = random.Random(9711)
        (self.source / "data & names" / "random.bin").write_bytes(rng.randbytes(1_700_123))
        (self.source / "compressible.bin").write_bytes((b"FFPFSC round trip\x00" * 100_000) + b"tail")
        self.expected = hashes(self.source)

    def tearDown(self):
        self.temp.cleanup()

    def extract_and_compare(self, image, name="out", expect_empty=False):
        before = hashlib.sha256(image.read_bytes()).digest()
        with contextlib.redirect_stdout(io.StringIO()):
            dump = worker.extract(image, self.root / name, self.root / (name + ".xml"), True)
        self.assertEqual(hashes(dump), self.expected)
        if expect_empty:
            self.assertTrue((dump / "empty-directory").is_dir())
        self.assertEqual(hashlib.sha256(image.read_bytes()).digest(), before)
        return dump

    def test_raw_pfs(self):
        image = self.root / "game.ffpfs"
        pack(self.source, image)
        self.extract_and_compare(image)

    def test_compressed_files(self):
        image = self.root / "game.ffpfsc"
        pack(self.source, image, compress=True)
        self.extract_and_compare(image)

    def test_signed_32_and_64(self):
        for bits in (32, 64):
            with self.subTest(bits=bits):
                image = self.root / f"signed-{bits}.ffpfs"
                pack(self.source, image, compress=True, signed=True, bits=bits)
                self.extract_and_compare(image, "out-" + str(bits))

    def test_ffpfsc_wrapped_exfat(self):
        (self.source / "data & names").rename(self.source / "dati & caffè")
        self.expected = hashes(self.source)
        image = self.root / "inner.exfat"
        with image.open("wb") as f:
            for block in iter_exfat_image(self.source):
                f.write(block)
        outer = self.root / "game.ffpfsc"
        wrap(image, outer)
        dump = self.extract_and_compare(outer, expect_empty=True)
        self.assertEqual(dump.name, "layer-0", "Inner exFAT must be decoded on demand, with no temporary disk image")

    def test_nested_pfs(self):
        inner = self.root / "inner.pfs"
        pack(self.source, inner, compress=True)
        outer = self.root / "game.ffpfsc"
        wrap(inner, outer)
        self.extract_and_compare(outer)
        self.assertFalse((self.root / "out" / "layer-0").exists())

    def test_reject_corrupt_compressed_payload(self):
        image = self.root / "damaged.ffpfsc"
        pack(self.source, image, compress=True)
        inspection = pfs.inspect_pfs_image(image, verify_payloads=False)
        inode = inspection.inodes[inspection.file_inodes["compressible.bin"]]
        self.assertTrue(inode.is_compressed)
        base = inode.db[0] * inspection.header.block_size
        with image.open("r+b") as file:
            file.seek(base)
            _, _, table, _, _ = pfs._parse_pfsc_header(file.read(48))
            file.seek(base + table)
            start, end = struct.unpack("<QQ", file.read(16))
            self.assertLess(end - start, 65536)
            file.seek(base + end - 1)
            value = file.read(1)[0]
            file.seek(base + end - 1)
            file.write(bytes([value ^ 0x40]))
        with contextlib.redirect_stdout(io.StringIO()), self.assertRaises(Exception):
            worker.extract(image, self.root / "bad", self.root / "bad.xml", True)
        self.assertFalse((self.root / "bad.xml").exists())

    def test_reject_truncated_and_wrong_headers(self):
        image = self.root / "truncated.ffpfsc"
        pack(self.source, image)
        with image.open("r+b") as file:
            file.truncate(1024)
        with contextlib.redirect_stdout(io.StringIO()), self.assertRaises(ValueError):
            worker.extract(image, self.root / "bad", self.root / "bad.xml", True)
        wrong = self.root / "renamed.ffpfsc"
        wrong.write_bytes(b"not a PFS file" * 200)
        with contextlib.redirect_stdout(io.StringIO()), self.assertRaises(ValueError):
            worker.extract(wrong, self.root / "wrong", self.root / "wrong.xml", True)

    def test_no_overwrite(self):
        image = self.root / "game.ffpfs"
        pack(self.source, image)
        existing = self.root / "out"
        existing.mkdir()
        marker = existing / "keep.txt"
        marker.write_text("original")
        with self.assertRaises(FileExistsError):
            worker.extract(image, existing, self.root / "out.xml", True)
        self.assertEqual(marker.read_text(), "original")

    def test_paths_before_any_file_is_written(self):
        for index, name in enumerate(("../escape", "/escape", "C:\\escape", "data:stream", "NUL.txt", "trailing. ")):
            with self.subTest(name=name), self.assertRaises(ValueError):
                worker.write_tree(self.root / f"unsafe-{index}", [], [(name, 1, None)], lambda _: [b"x"], True)
        with self.assertRaises(ValueError):
            worker.write_tree(self.root / "case-collision", [], [("A.bin", 1, None), ("a.bin", 1, None)], lambda _: [b"x"], True)
        self.assertFalse((self.root / "escape").exists())
        self.assertFalse((self.root / "case-collision").exists())


if __name__ == "__main__":
    unittest.main(verbosity=2)
