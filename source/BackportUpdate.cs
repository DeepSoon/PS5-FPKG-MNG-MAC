    internal static class BackportVersion
    {
        private static readonly Regex Pattern = new Regex("^[0-9]{2}\\.[0-9]{3}\\.[0-9]{3}$", RegexOptions.CultureInvariant);

        internal static bool IsValid(string value) { return !string.IsNullOrEmpty(value) && Pattern.IsMatch(value.Trim()); }

        internal static int Compare(string left, string right)
        {
            int[] a = Parts(left), b = Parts(right);
            for (int i = 0; i < a.Length; i++)
            {
                if (a[i] < b[i]) return -1;
                if (a[i] > b[i]) return 1;
            }
            return 0;
        }

        internal static string Next(string value)
        {
            int[] parts = Parts(value);
            if (parts[2] < 999) parts[2]++;
            else if (parts[1] < 999) { parts[1]++; parts[2] = 0; }
            else if (parts[0] < 99) { parts[0]++; parts[1] = 0; parts[2] = 0; }
            else throw new ArgumentException("The base version is already at the maximum supported value.");
            return parts[0].ToString("00", CultureInfo.InvariantCulture) + "." +
                parts[1].ToString("000", CultureInfo.InvariantCulture) + "." +
                parts[2].ToString("000", CultureInfo.InvariantCulture);
        }

        private static int[] Parts(string value)
        {
            if (!IsValid(value)) throw new ArgumentException("Use a version like 01.001.005.");
            string[] fields = value.Trim().Split('.');
            return new int[] { int.Parse(fields[0], CultureInfo.InvariantCulture),
                int.Parse(fields[1], CultureInfo.InvariantCulture), int.Parse(fields[2], CultureInfo.InvariantCulture) };
        }
    }

    internal static class BackportPath
    {
        internal static string NormalizeRelative(string value)
        {
            if (string.IsNullOrWhiteSpace(value)) throw new ArgumentException("A file path inside the game is required.");
            string path = value.Trim().Replace('\\', '/');
            if (path.StartsWith("/", StringComparison.Ordinal) || Regex.IsMatch(path, "^[A-Za-z]:") || Path.IsPathRooted(path))
                throw new ArgumentException("Use a path relative to the game root, for example sce_module/libc.prx.");
            string[] pieces = path.Split('/');
            List<string> normalized = new List<string>();
            foreach (string piece in pieces)
            {
                if (piece.Length == 0) continue;
                if (piece == "." || piece == "..") throw new ArgumentException("The path cannot contain . or .. folders.");
                if (piece.TrimEnd(' ', '.').Length != piece.Length || piece.IndexOfAny(new char[] { '<', '>', ':', '"', '|', '?', '*' }) >= 0)
                    throw new ArgumentException("The path contains a character that Windows cannot save in a file name.");
                normalized.Add(piece);
            }
            if (normalized.Count == 0) throw new ArgumentException("A file name is required.");
            return string.Join("/", normalized.ToArray());
        }

        internal static string SkipReason(string relative)
        {
            string path = NormalizeRelative(relative).ToLowerInvariant();
            if (path.StartsWith("sce_sys/about/", StringComparison.Ordinal)) return "sce_sys/about is generated by the SDK";
            if (path.EndsWith(".esbak", StringComparison.Ordinal)) return "backup file created by the patcher";
            if (path == "sce_sys/keystone") return "the keystone from the base game is kept";
            if (path == "sce_sys/icon0.dds" || path == "sce_sys/pfs-version.dat" || path == "sce_sys/pic0.dds" ||
                path == "sce_sys/pic1.dds" || path == "sce_sys/pic2.dds" || path == "sce_sys/playgo-scenario.json")
                return "generated or reserved sce_sys file";
            if (path == "fakelib/libsceampr.sprx" || path == "fakelib/libsceplaygo.sprx")
                return "SDK/runtime module is not included in the update overlay";
            return null;
        }

        internal static string NormalizeDirectoryPrefix(string value)
        {
            if (string.IsNullOrWhiteSpace(value)) return string.Empty;
            string trimmed = value.Trim().TrimEnd('/', '\\');
            return NormalizeRelative(trimmed);
        }
    }

    internal sealed class BackportFileItem
    {
        internal string RelativePath;
        internal string OriginalSourcePath;
        internal string ReplacementSourcePath;
        internal string SkipReason;
        internal bool Include;
        internal bool Added;

        internal string EffectiveSource { get { return string.IsNullOrEmpty(ReplacementSourcePath) ? OriginalSourcePath : ReplacementSourcePath; } }
        internal long Length { get { return File.Exists(EffectiveSource) ? new FileInfo(EffectiveSource).Length : 0; } }
    }

    internal sealed class BackportFileSet
    {
        internal string Root { get; private set; }
        internal readonly List<BackportFileItem> Items = new List<BackportFileItem>();

        private BackportFileSet(string root) { Root = root; }

        internal static BackportFileSet Load(string root)
        {
            if (string.IsNullOrWhiteSpace(root) || !Directory.Exists(root)) throw new DirectoryNotFoundException("Select the backport folder first.");
            root = Path.GetFullPath(root);
            FileWorkspace.NoReparse(root);
            BackportFileSet result = new BackportFileSet(root);
            Stack<string> pending = new Stack<string>();
            pending.Push(root);
            while (pending.Count != 0)
            {
                string directory = pending.Pop();
                foreach (string entry in Directory.GetFileSystemEntries(directory))
                {
                    FileAttributes attributes = File.GetAttributes(entry);
                    if ((attributes & FileAttributes.ReparsePoint) != 0) continue;
                    if ((attributes & FileAttributes.Directory) != 0) { pending.Push(entry); continue; }
                    string relative = entry.Substring(root.Length).TrimStart(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar).Replace('\\', '/');
                    string safe = BackportPath.NormalizeRelative(relative);
                    if (safe.EndsWith(".esbak", StringComparison.OrdinalIgnoreCase)) continue;
                    string skip = BackportPath.SkipReason(safe);
                    result.Items.Add(new BackportFileItem { RelativePath = safe, OriginalSourcePath = entry,
                        Include = skip == null, SkipReason = skip, Added = false });
                }
            }
            result.Items.Sort(delegate(BackportFileItem a, BackportFileItem b) { return StringComparer.OrdinalIgnoreCase.Compare(a.RelativePath, b.RelativePath); });
            return result;
        }

        internal BackportFileItem Find(string relative)
        {
            string safe = BackportPath.NormalizeRelative(relative);
            return Items.Find(delegate(BackportFileItem item) { return item.RelativePath.Equals(safe, StringComparison.OrdinalIgnoreCase); });
        }

        internal void Add(string source, string relative)
        {
            source = ValidateSourceFile(source);
            string safe = BackportPath.NormalizeRelative(relative);
            string skip = BackportPath.SkipReason(safe);
            if (skip != null) throw new ArgumentException("This file cannot be added: " + skip + ".");
            if (Find(safe) != null) throw new IOException("A file with this game path is already in the list. Use Replace instead.");
            Items.Add(new BackportFileItem { RelativePath = safe, OriginalSourcePath = source, Include = true, Added = true });
            Sort();
        }

        internal void AddFolder(string sourceFolder, string relativePrefix)
        {
            if (!Directory.Exists(sourceFolder)) throw new DirectoryNotFoundException("Folder to add was not found.");
            sourceFolder = Path.GetFullPath(sourceFolder);
            FileWorkspace.NoReparse(sourceFolder);
            string prefix = BackportPath.NormalizeDirectoryPrefix(relativePrefix);
            List<KeyValuePair<string, string>> additions = new List<KeyValuePair<string, string>>();
            Stack<string> pending = new Stack<string>(); pending.Push(sourceFolder);
            while (pending.Count != 0)
            {
                string directory = pending.Pop();
                foreach (string entry in Directory.GetFileSystemEntries(directory))
                {
                    FileAttributes attributes = File.GetAttributes(entry);
                    if ((attributes & FileAttributes.ReparsePoint) != 0) continue;
                    if ((attributes & FileAttributes.Directory) != 0) { pending.Push(entry); continue; }
                    string local = entry.Substring(sourceFolder.Length).TrimStart(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar).Replace('\\', '/');
                    string destination = string.IsNullOrEmpty(prefix) ? local : prefix + "/" + local;
                    additions.Add(new KeyValuePair<string, string>(ValidateSourceFile(entry), BackportPath.NormalizeRelative(destination)));
                }
            }
            HashSet<string> planned = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (KeyValuePair<string, string> item in additions)
            {
                string skip = BackportPath.SkipReason(item.Value);
                if (skip != null) throw new ArgumentException("This file cannot be added: " + skip + ".");
                if (!planned.Add(item.Value) || Find(item.Value) != null)
                    throw new IOException("A file with this game path is already in the list. No files from the folder were added.");
            }
            foreach (KeyValuePair<string, string> item in additions) Add(item.Key, item.Value);
        }

        internal void Replace(string relative, string replacement)
        {
            BackportFileItem item = Find(relative);
            if (item == null) throw new FileNotFoundException("The selected game path is not in the list.", relative);
            if (!string.IsNullOrEmpty(item.SkipReason)) throw new ArgumentException("This file is reserved by the SDK and cannot be replaced: " + item.SkipReason + ".");
            item.ReplacementSourcePath = ValidateSourceFile(replacement);
            item.Include = true;
        }

        internal void IncludeFile(string relative, bool include)
        {
            BackportFileItem item = Find(relative);
            if (item == null) throw new FileNotFoundException("The selected game path is not in the list.", relative);
            if (include && !string.IsNullOrEmpty(item.SkipReason)) throw new ArgumentException("This file cannot be included: " + item.SkipReason + ".");
            item.Include = include;
        }

        internal int Stage(string destination, Action<string> log, CancellationToken token)
        {
            destination = Path.GetFullPath(destination);
            if (Directory.Exists(destination) || File.Exists(destination)) throw new IOException("The temporary overlay already exists.");
            int selected = 0;
            foreach (BackportFileItem item in Items)
                if (item.Include && string.IsNullOrEmpty(item.SkipReason)) selected++;
            if (selected == 0) throw new InvalidDataException("Seleziona almeno un file da salvare.");
            string parent = Path.GetDirectoryName(destination);
            if (string.IsNullOrEmpty(parent)) throw new ArgumentException("Choose an overlay destination folder.");
            Directory.CreateDirectory(parent);
            string stagingRoot = FileWorkspace.CreateOwned(parent);
            string staged = Path.Combine(stagingRoot, "overlay");
            try
            {
                Directory.CreateDirectory(staged);
                int copied = 0;
                foreach (BackportFileItem item in Items)
                {
                    token.ThrowIfCancellationRequested();
                    if (!item.Include) continue;
                    if (!string.IsNullOrEmpty(item.SkipReason)) throw new InvalidDataException("Reserved file was incorrectly selected: " + item.RelativePath);
                    string source = ValidateSourceFile(item.EffectiveSource);
                    string target = Path.GetFullPath(Path.Combine(staged, item.RelativePath.Replace('/', Path.DirectorySeparatorChar)));
                    if (!FileWorkspace.Inside(target, staged)) throw new InvalidDataException("Backport path escapes the temporary overlay.");
                    Directory.CreateDirectory(Path.GetDirectoryName(target));
                    using (FileStream input = new FileStream(source, FileMode.Open, FileAccess.Read, FileShare.Read, 1024 * 1024, FileOptions.SequentialScan))
                    using (FileStream output = new FileStream(target, FileMode.CreateNew, FileAccess.Write, FileShare.None, 1024 * 1024, FileOptions.SequentialScan))
                    {
                        byte[] buffer = new byte[1024 * 1024]; int count;
                        while ((count = input.Read(buffer, 0, buffer.Length)) != 0)
                        { token.ThrowIfCancellationRequested(); output.Write(buffer, 0, count); }
                    }
                    copied++;
                    if (log != null) log("+ " + item.RelativePath + (item.Added ? " (new)" : ""));
                }
                token.ThrowIfCancellationRequested();
                if (Directory.Exists(destination) || File.Exists(destination)) throw new IOException("The overlay destination appeared while files were being saved.");
                Directory.Move(staged, destination);
                return copied;
            }
            finally { FileWorkspace.DeleteOwned(stagingRoot, log); }
        }

        internal void Extract(IEnumerable<BackportFileItem> files, string destination, CancellationToken token)
        {
            if (!Directory.Exists(destination)) throw new DirectoryNotFoundException("Choose an existing extraction folder.");
            destination = Path.GetFullPath(destination);
            foreach (BackportFileItem item in files)
            {
                token.ThrowIfCancellationRequested();
                string source = ValidateSourceFile(item.EffectiveSource);
                string target = Path.GetFullPath(Path.Combine(destination, item.RelativePath.Replace('/', Path.DirectorySeparatorChar)));
                if (!FileWorkspace.Inside(target, destination)) throw new InvalidDataException("Backport path escapes the extraction folder.");
                if (File.Exists(target) || Directory.Exists(target)) throw new IOException("Extraction would overwrite an existing path: " + target);
                Directory.CreateDirectory(Path.GetDirectoryName(target));
                File.Copy(source, target, false);
            }
        }

        internal long IncludedBytes()
        {
            long total = 0;
            foreach (BackportFileItem item in Items) if (item.Include && string.IsNullOrEmpty(item.SkipReason)) total = checked(total + item.Length);
            return total;
        }

        private void Sort() { Items.Sort(delegate(BackportFileItem a, BackportFileItem b) { return StringComparer.OrdinalIgnoreCase.Compare(a.RelativePath, b.RelativePath); }); }

        private static string ValidateSourceFile(string source)
        {
            if (string.IsNullOrWhiteSpace(source) || !File.Exists(source)) throw new FileNotFoundException("Selected file was not found.", source);
            source = Path.GetFullPath(source);
            FileWorkspace.NoReparse(source);
            if ((File.GetAttributes(source) & FileAttributes.Directory) != 0) throw new ArgumentException("Select a file, not a folder.");
            return source;
        }
    }

    internal sealed class BackportUpdateRequest
    {
        internal string BasePackage;
        internal string GameFolder;
        internal string BackportFolder;
        internal string OutputPackage;
        internal string WorkParent;
        internal string PublisherTool;
        internal string Passcode;
        internal string ContentVersion;
        internal int CompressionLevel;
        internal BackportFileSet Files;
    }

    internal static class BackportUpdateJob
    {
        internal static string Run(BackportUpdateRequest request, CancellationToken token,
            Action<ConversionProgress> report, Action<string> log)
        {
            string work = null;
            string persistentLog = null;
            FileStream baseGuard = null;
            try
            {
                Validate(request);
                token.ThrowIfCancellationRequested();
                report(new ConversionProgress("Controllo PKG base", "Leggo solo intestazione e metadati CNT", 0, 0));
                baseGuard = new FileStream(request.BasePackage, FileMode.Open, FileAccess.Read, FileShare.Read);
                PackageSnapshot snapshot = CntMetadata.ReadSmall(baseGuard, request.BasePackage, request.Passcode).Snapshot;
                PackageParam baseParam = new PackageParam(snapshot.ParamBytes);
                if (!BackportVersion.IsValid(snapshot.ContentVersion))
                    throw new InvalidDataException("La versione del PKG base non ha il formato 01.001.004. Il pacchetto non è stato modificato.");
                if (!BackportVersion.IsValid(request.ContentVersion) || BackportVersion.Compare(request.ContentVersion, snapshot.ContentVersion) <= 0)
                    throw new ArgumentException("La versione dell’aggiornamento deve essere nel formato 01.001.005 e maggiore di " + snapshot.ContentVersion + ".");
                if (!string.Equals(snapshot.ContentId, baseParam.Text("contentId"), StringComparison.Ordinal))
                    throw new InvalidDataException("Il Content ID dei metadati non coincide con il PKG base.");

                string gameParamPath = Path.Combine(request.GameFolder, "sce_sys", "param.json");
                if (!File.Exists(gameParamPath)) throw new FileNotFoundException("Nella cartella gioco manca sce_sys/param.json.", gameParamPath);
                FileWorkspace.NoReparse(gameParamPath);
                PackageParam gameParam = new PackageParam(File.ReadAllBytes(gameParamPath));
                ValidateGameFolderMatch(snapshot, gameParam);
                string keystone = Path.Combine(request.GameFolder, "sce_sys", "keystone");
                if (!File.Exists(keystone) || new FileInfo(keystone).Length != 96)
                    throw new InvalidDataException("Nella cartella gioco serve sce_sys/keystone da 96 byte.");
                FileWorkspace.NoReparse(keystone);

                int chosen = 0;
                foreach (BackportFileItem item in request.Files.Items)
                    if (item.Include && string.IsNullOrEmpty(item.SkipReason)) chosen++;
                if (chosen == 0) throw new InvalidDataException("Seleziona almeno un file da inserire nell’aggiornamento.");

                string outputParent = Path.GetDirectoryName(Path.GetFullPath(request.OutputPackage));
                string logDirectory = Path.Combine(outputParent, Path.GetFileNameWithoutExtension(request.BasePackage) + "-backport-logs");
                Directory.CreateDirectory(logDirectory);
                string logStem = "img-create-" + DateTime.Now.ToString("yyyyMMdd-HHmmss", CultureInfo.InvariantCulture);
                persistentLog = Path.Combine(logDirectory, logStem + ".log");
                int logSuffix = 1;
                while (File.Exists(persistentLog)) persistentLog = Path.Combine(logDirectory, logStem + "-" + (logSuffix++) + ".log");
                string gameRoot = Path.GetFullPath(request.GameFolder);
                if (FileWorkspace.Inside(outputParent, gameRoot) || FileWorkspace.Inside(request.WorkParent, gameRoot))
                    throw new ArgumentException("Cartella di output e lavoro devono stare fuori dalla cartella completa del gioco.");
                if (FileWorkspace.Inside(request.BackportFolder, gameRoot))
                    throw new ArgumentException("La cartella backport deve stare fuori dalla cartella completa del gioco.");

                long free = FileWorkspace.FreeBytes(request.WorkParent);
                long baseSize = new FileInfo(request.BasePackage).Length;
                log("Base: " + request.BasePackage);
                log("Contenuto: " + snapshot.ContentId + "; versione base " + snapshot.ContentVersion + "; aggiornamento " + request.ContentVersion);
                log("La cartella gioco verrà letta in place. I dati copiati nella cartella di lavoro sono solo i file selezionati e param.json.");
                if (free < baseSize)
                    log("AVVISO: nello spazio di lavoro ci sono " + FileWorkspace.Size(free) + " liberi; il publisher potrebbe aver bisogno di circa " + FileWorkspace.Size(baseSize) + " per i file temporanei/remastered.");
                else
                    log("Spazio di lavoro: " + FileWorkspace.Size(free) + " liberi; il PKG base misura " + FileWorkspace.Size(baseSize) + ".");

                work = FileWorkspace.CreateOwned(request.WorkParent);
                string overlay = Path.Combine(work, "overlay");
                string gp5 = Path.Combine(work, "project.gp5");
                string partial = Path.Combine(work, "update.partial.pkg");
                string publisherTemp = Path.Combine(work, "publisher-temp");
                Directory.CreateDirectory(publisherTemp);

                report(new ConversionProgress("Preparo i file scelti", "Copio solo il backport selezionato", 0, request.Files.IncludedBytes()));
                request.Files.Stage(overlay, log, token);
                token.ThrowIfCancellationRequested();

                string stagedParam = Path.Combine(overlay, "sce_sys", "param.json");
                byte[] paramBytes = File.Exists(stagedParam) ? File.ReadAllBytes(stagedParam) : snapshot.ParamBytes;
                PackageParam updateParam = new PackageParam(paramBytes);
                if (!string.Equals(snapshot.ContentId, updateParam.Text("contentId"), StringComparison.OrdinalIgnoreCase))
                    throw new InvalidDataException("Il param.json del backport appartiene a un Content ID diverso dal PKG base.");
                updateParam.SetText("contentVersion", request.ContentVersion.Trim());
                Directory.CreateDirectory(Path.GetDirectoryName(stagedParam));
                File.WriteAllBytes(stagedParam, updateParam.Bytes());

                Dictionary<string, string> overlayFiles = ReadOverlayFiles(overlay);
                overlayFiles["sce_sys/param.json"] = stagedParam;
                report(new ConversionProgress("Creo il progetto GP5", "Elenco i file del gioco e collego quelli aggiornati", 0, 0));
                int mappings = CreatePatchProject(gameRoot, overlayFiles, keystone, gp5, request.Passcode, log);
                token.ThrowIfCancellationRequested();
                log("Progetto GP5 creato: " + mappings + " file mappati; i file originali restano nelle loro cartelle.");

                byte[] referenceDigest = ReadReferenceDigest(baseGuard);
                report(new ConversionProgress("Creo il PKG aggiornamento", "Il publisher SDK può leggere molti file e usare spazio temporaneo", 0, 0));
                log("Avvio img_create. Il PKG base resta bloccato in sola lettura e non verrà riscritto.");
                string[] args = new string[] { "img_create", "--oformat", "nwonly", "--compression_level",
                    request.CompressionLevel.ToString(CultureInfo.InvariantCulture), "--no_progress_bar", "--ref_pkg_path",
                    request.BasePackage, gp5, partial };
                object processLogGate = new object();
                Action<string> processLog = delegate(string line)
                {
                    if (log != null) log(line);
                    try { lock (processLogGate) File.AppendAllText(persistentLog, line + Environment.NewLine, Encoding.UTF8); } catch { }
                };
                try { File.WriteAllText(persistentLog, "img_create log · " + DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss", CultureInfo.InvariantCulture) + Environment.NewLine, Encoding.UTF8); } catch { }
                Dictionary<string, string> environment = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
                { { "TEMP", publisherTemp }, { "TMP", publisherTemp } };
                ToolResult result = ProcessRunner.RunWithEnvironment(request.PublisherTool, args, 0, token, processLog, work, environment);
                if (result.ExitCode != 0) throw new IOException("img_create è terminato con codice " + result.ExitCode + ". Log: " + persistentLog);
                if (!File.Exists(partial) || new FileInfo(partial).Length == 0)
                    throw new IOException("img_create è terminato senza creare il PKG aggiornamento.");
                if (!ContainsBytes(partial, referenceDigest, token))
                    throw new InvalidDataException("Il PKG generato non contiene il digest del PKG base. Non lo salvo perché potrebbe non essere installabile su quel base.");

                report(new ConversionProgress("Salvo aggiornamento", "Pubblico il solo PKG delta", 0, new FileInfo(partial).Length));
                CommitNewFile(partial, request.OutputPackage, token, report);
                log("Aggiornamento creato e verificato: " + request.OutputPackage);
                return request.OutputPackage;
            }
            finally
            {
                if (baseGuard != null) baseGuard.Dispose();
                if (work != null) FileWorkspace.DeleteOwned(work, log);
            }
        }

        private static void Validate(BackportUpdateRequest request)
        {
            if (request == null) throw new ArgumentNullException("request");
            request.BasePackage = Path.GetFullPath((request.BasePackage ?? string.Empty).Trim());
            request.GameFolder = Path.GetFullPath((request.GameFolder ?? string.Empty).Trim());
            request.BackportFolder = Path.GetFullPath((request.BackportFolder ?? string.Empty).Trim());
            request.OutputPackage = Path.GetFullPath((request.OutputPackage ?? string.Empty).Trim());
            request.WorkParent = Path.GetFullPath((request.WorkParent ?? string.Empty).Trim());
            request.PublisherTool = Path.GetFullPath((request.PublisherTool ?? string.Empty).Trim());
            request.Passcode = string.IsNullOrEmpty(request.Passcode) ? new string('0', 32) : request.Passcode.Trim();
            if (!File.Exists(request.BasePackage) || !Path.GetExtension(request.BasePackage).Equals(".pkg", StringComparison.OrdinalIgnoreCase))
                throw new FileNotFoundException("Seleziona il PKG base (.pkg).", request.BasePackage);
            if (!Directory.Exists(request.GameFolder)) throw new DirectoryNotFoundException("Seleziona la cartella completa del gioco.");
            if (!Directory.Exists(request.BackportFolder)) throw new DirectoryNotFoundException("Seleziona la cartella dei file backport.");
            if (request.Files == null || !Path.GetFullPath(request.BackportFolder).Equals(Path.GetFullPath(request.Files.Root), StringComparison.OrdinalIgnoreCase))
                throw new ArgumentException("Ricarica la cartella backport prima di creare l’aggiornamento.");
            if (!File.Exists(request.PublisherTool) || !Path.GetFileName(request.PublisherTool).Equals("prospero-pub-cmd.exe", StringComparison.OrdinalIgnoreCase))
                throw new FileNotFoundException("Seleziona prospero-pub-cmd.exe del SDK PlayStation 5.", request.PublisherTool);
            if (request.Passcode.Length != 32) throw new ArgumentException("Il passcode PKG deve contenere esattamente 32 caratteri.");
            if (!BackportVersion.IsValid(request.ContentVersion)) throw new ArgumentException("Inserisci la versione nel formato 01.001.005.");
            if (request.CompressionLevel < 0 || request.CompressionLevel > 9) throw new ArgumentOutOfRangeException("CompressionLevel");
            if (!Path.GetExtension(request.OutputPackage).Equals(".pkg", StringComparison.OrdinalIgnoreCase)) throw new ArgumentException("Il nome di output deve terminare con .pkg.");
            if (request.BasePackage.Equals(request.OutputPackage, StringComparison.OrdinalIgnoreCase)) throw new ArgumentException("Il PKG aggiornamento deve avere un nome diverso dal PKG base.");
            if (File.Exists(request.OutputPackage) || Directory.Exists(request.OutputPackage)) throw new IOException("Il file di output esiste già. Scegli un nome o una cartella diversa.");
            if (!Directory.Exists(Path.GetDirectoryName(request.OutputPackage))) throw new DirectoryNotFoundException("La cartella di output non esiste.");
            if (!Directory.Exists(request.WorkParent)) throw new DirectoryNotFoundException("La cartella di lavoro non esiste.");
            FileWorkspace.NoReparse(request.BasePackage); FileWorkspace.NoReparse(request.GameFolder); FileWorkspace.NoReparse(request.BackportFolder);
        }

        internal static void ValidateGameFolderMatch(PackageSnapshot snapshot, PackageParam gameParam)
        {
            if (snapshot == null) throw new ArgumentNullException("snapshot");
            if (gameParam == null) throw new ArgumentNullException("gameParam");
            if (!string.Equals(snapshot.ContentId, gameParam.Text("contentId"), StringComparison.OrdinalIgnoreCase))
                throw new InvalidDataException("La cartella gioco e il PKG base hanno Content ID diversi.");
            string folderVersion = gameParam.Text("contentVersion");
            if (!BackportVersion.IsValid(folderVersion) || !BackportVersion.IsValid(snapshot.ContentVersion) ||
                BackportVersion.Compare(folderVersion, snapshot.ContentVersion) != 0)
                throw new InvalidDataException("La cartella gioco deve provenire dalla stessa versione del PKG base (" + snapshot.ContentVersion + ").");
        }

        private static Dictionary<string, string> ReadOverlayFiles(string root)
        {
            Dictionary<string, string> result = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            foreach (string file in Directory.GetFiles(root, "*", SearchOption.AllDirectories))
            {
                FileWorkspace.NoReparse(file);
                string relative = file.Substring(root.Length).TrimStart(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar).Replace('\\', '/');
                relative = BackportPath.NormalizeRelative(relative);
                if (BackportPath.SkipReason(relative) != null) continue;
                if (result.ContainsKey(relative)) throw new InvalidDataException("Duplicate overlay path: " + relative);
                result.Add(relative, file);
            }
            return result;
        }

        internal static int CreatePatchProject(string gameRoot, Dictionary<string, string> overlay, string keystone,
            string gp5Path, string passcode, Action<string> log)
        {
            Type creator = BuilderBridge.Library.GetType("LibProsperoPkg.GP5.Gp5Creator", true);
            Type volumeType = BuilderBridge.Library.GetType("LibProsperoPkg.GP5.Gp5VolumeType", true);
            Type projectType = BuilderBridge.Library.GetType("LibProsperoPkg.GP5.Gp5Project", true);
            Type fileType = BuilderBridge.Library.GetType("LibProsperoPkg.GP5.Gp5File", true);
            MethodInfo fromFolder = creator.GetMethod("FromFolderExplicit", BuilderBridge.Members, null,
                new Type[] { typeof(string), volumeType, typeof(string) }, null);
            if (fromFolder == null) throw new MissingMethodException(creator.FullName, "FromFolderExplicit");
            object volume = Enum.Parse(volumeType, "prospero_patch", false);
            object project = BuilderBridge.Invoke(fromFolder, null, gameRoot, volume, passcode);
            IList files = BuilderBridge.Get(project, "Files") as IList;
            if (files == null) throw new InvalidDataException("La libreria GP5 non espone l’elenco file modificabile.");

            for (int i = files.Count - 1; i >= 0; i--)
            {
                string destination = ReadString(files[i], "DestinationPath");
                string normalized = BackportPath.NormalizeRelative(destination);
                if (BackportPath.SkipReason(normalized) != null) files.RemoveAt(i);
            }

            Dictionary<string, int> byDestination = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
            for (int i = files.Count - 1; i >= 0; i--)
            {
                object entry = files[i];
                string destination = ReadString(entry, "DestinationPath");
                string normalized = BackportPath.NormalizeRelative(destination);
                if (byDestination.ContainsKey(normalized)) throw new InvalidDataException("GP5 contiene due mappature per " + normalized);
                byDestination.Add(normalized, i);
            }

            foreach (KeyValuePair<string, string> pair in overlay)
            {
                if (BackportPath.SkipReason(pair.Key) != null) continue;
                int index;
                if (byDestination.TryGetValue(pair.Key, out index))
                {
                    object entry = files[index];
                    WriteString(entry, "SourcePath", pair.Value);
                    files[index] = entry;
                }
                else
                {
                    object entry = Activator.CreateInstance(fileType);
                    WriteString(entry, "SourcePath", pair.Value);
                    WriteString(entry, "DestinationPath", pair.Key);
                    files.Add(entry);
                    byDestination.Add(pair.Key, files.Count - 1);
                }
            }

            int keystoneIndex;
            if (!byDestination.TryGetValue("sce_sys/keystone", out keystoneIndex))
            {
                object entry = Activator.CreateInstance(fileType);
                WriteString(entry, "SourcePath", keystone);
                WriteString(entry, "DestinationPath", "sce_sys/keystone");
                files.Add(entry);
                byDestination.Add("sce_sys/keystone", files.Count - 1);
            }
            else
            {
                object entry = files[keystoneIndex];
                WriteString(entry, "SourcePath", keystone);
                files[keystoneIndex] = entry;
            }

            MethodInfo write = projectType.GetMethod("WriteTo", BuilderBridge.Members, null,
                new Type[] { projectType, typeof(string) }, null);
            if (write != null) BuilderBridge.Invoke(write, null, project, gp5Path);
            else
            {
                write = projectType.GetMethod("WriteTo", BuilderBridge.Members, null, new Type[] { typeof(string) }, null);
                if (write == null) throw new MissingMethodException(projectType.FullName, "WriteTo");
                BuilderBridge.Invoke(write, project, gp5Path);
            }
            if (!File.Exists(gp5Path) || new FileInfo(gp5Path).Length == 0) throw new IOException("Il progetto GP5 non è stato scritto.");
            if (log != null) log("Mappature GP5: "+ files.Count + "; file modificati/aggiunti: " + overlay.Count + ".");
            return files.Count;
        }

        private static string ReadString(object target, string member)
        {
            object value = BuilderBridge.Get(target, member);
            return Convert.ToString(value, CultureInfo.InvariantCulture) ?? string.Empty;
        }

        private static void WriteString(object target, string member, string value)
        {
            PropertyInfo property = target.GetType().GetProperty(member, BuilderBridge.Members);
            if (property != null && property.CanWrite) { property.SetValue(target, value, null); return; }
            FieldInfo field = target.GetType().GetField(member, BuilderBridge.Members);
            if (field != null) { field.SetValue(target, value); return; }
            throw new MissingMemberException(target.GetType().FullName, member);
        }

        private static byte[] ReadReferenceDigest(Stream basePackage)
        {
            byte[] header = PackageSdk.ReadRange(basePackage, 0, 65536);
            if (header[0] != 0x7f || header[1] != 'F' || header[2] != 'I' || header[3] != 'H')
                throw new NotSupportedException("Il PKG scelto non è un’immagine PS5 FIH utilizzabile come riferimento.");
            return BinaryData.Slice(header, 0x30, 32);
        }

        private static bool ContainsBytes(string path, byte[] needle, CancellationToken token)
        {
            byte[] buffer = new byte[1024 * 1024];
            int overlap = needle.Length - 1;
            int carry = 0;
            using (FileStream input = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read, buffer.Length, FileOptions.SequentialScan))
            {
                while (true)
                {
                    token.ThrowIfCancellationRequested();
                    int read = input.Read(buffer, carry, buffer.Length - carry);
                    if (read == 0) return false;
                    int available = carry + read;
                    for (int i = 0; i <= available - needle.Length; i++)
                    {
                        int j = 0;
                        while (j < needle.Length && buffer[i + j] == needle[j]) j++;
                        if (j == needle.Length) return true;
                    }
                    carry = Math.Min(overlap, available);
                    Buffer.BlockCopy(buffer, available - carry, buffer, 0, carry);
                }
            }
        }

        private static void CommitNewFile(string staged, string target, CancellationToken token, Action<ConversionProgress> report)
        {
            if (File.Exists(target) || Directory.Exists(target)) throw new IOException("Il file di output è stato creato durante la compilazione: " + target);
            string stagedRoot = Path.GetPathRoot(Path.GetFullPath(staged));
            string targetRoot = Path.GetPathRoot(Path.GetFullPath(target));
            if (string.Equals(stagedRoot, targetRoot, StringComparison.OrdinalIgnoreCase))
            {
                token.ThrowIfCancellationRequested();
                File.Move(staged, target);
                report(new ConversionProgress("Salvo aggiornamento", "Spostamento atomico del delta", 1, 1));
                return;
            }
            string commit = target + ".tmp-" + Guid.NewGuid().ToString("N");
            byte[] buffer = new byte[4 * 1024 * 1024];
            try
            {
                using (FileStream input = new FileStream(staged, FileMode.Open, FileAccess.Read, FileShare.Read, buffer.Length, FileOptions.SequentialScan))
                using (FileStream output = new FileStream(commit, FileMode.CreateNew, FileAccess.Write, FileShare.None, buffer.Length, FileOptions.SequentialScan))
                {
                    long done = 0; int count;
                    while ((count = input.Read(buffer, 0, buffer.Length)) != 0)
                    { token.ThrowIfCancellationRequested(); output.Write(buffer, 0, count); done += count; report(new ConversionProgress("Salvo aggiornamento", "Copia del delta", done, input.Length)); }
                    output.Flush(true);
                }
                token.ThrowIfCancellationRequested();
                File.Move(commit, target);
            }
            finally { if (File.Exists(commit)) try { File.Delete(commit); } catch { } }
        }
